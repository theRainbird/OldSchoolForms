using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Reflection;
using System.Text;
using OldSchoolForms.Ui.Controls.Advanced;
using OldSchoolForms.Ui.Controls.Basic;
using OldSchoolForms.Ui.Controls.Containers;
using OldSchoolForms.Ui.Core;
using OldSchoolForms.Ui.Designer;
using OldSchoolForms.Ui.Designer.Services;
using OldSchoolForms.Ui.Layout;

namespace OldSchoolForms.Ui.Designer.Roslyn;

/// <summary>
/// Generates C# code for a Windows Forms-style InitializeComponent method
/// based on the controls placed on a <see cref="DesignSurface"/>.
/// </summary>
public class CodeGenerator
{
    private readonly DesignSurface _surface;
    private const string GeneratedClassName = "InitializeComponent";

    // C# keywords that can never be used as a field name without escaping.
    private static readonly HashSet<string> ReservedKeywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
        "class", "const", "continue", "decimal", "default", "delegate", "do", "double", "else",
        "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
        "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
        "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
        "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual",
        "void", "volatile", "while", "var", "global", "dynamic", "dyn"
    };

    // Property names emitted for every control; a field sharing one of these would hide the
    // inherited property and break the generated assignments.
    private static readonly HashSet<string> ReservedPropertyNames = new(StringComparer.Ordinal)
    {
        "Location", "Size", "Text", "Name", "BackColor", "TabIndex", "TabStop", "Enabled", "Visible", "Padding"
    };

    /// <summary>
    /// Initializes a new instance of the <see cref="CodeGenerator"/> class.
    /// </summary>
    /// <param name="surface">The design surface to generate code for.</param>
    /// <exception cref="ArgumentNullException">Thrown if surface is null.</exception>
    public CodeGenerator(DesignSurface surface)
    {
        _surface = surface ?? throw new ArgumentNullException(nameof(surface));
    }

    /// <summary>
    /// Generates the complete InitializeComponent method for the designed form.
    /// </summary>
    /// <param name="namespaceName">The namespace for the generated partial class.</param>
    /// <param name="className">The class name of the form.</param>
    /// <returns>A string containing the complete generated code.</returns>
    public string Generate(string namespaceName, string className)
    {
        var sb = new StringBuilder();

        sb.AppendLine("//------------------------------------------------------------------------------");
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     This code was generated by the OldSchoolForms Form Designer.");
        sb.AppendLine("//     Changes to this file may cause incorrect behavior and will be lost if");
        sb.AppendLine("//     the code is regenerated.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("//------------------------------------------------------------------------------");
        sb.AppendLine();
        sb.AppendLine("using OldSchoolForms.Ui.Core;");
        sb.AppendLine("using OldSchoolForms.Ui.Controls.Basic;");
        sb.AppendLine("using OldSchoolForms.Ui.Controls.Containers;");
        sb.AppendLine("using OldSchoolForms.Ui.Controls.Advanced;");
        sb.AppendLine("using OldSchoolForms.Ui.Layout;");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(namespaceName))
        {
            sb.AppendLine($"namespace {namespaceName}");
            sb.AppendLine("{");
        }

        var indent = !string.IsNullOrEmpty(namespaceName) ? "    " : "";
        sb.AppendLine($"{indent}partial class {className}");
        sb.AppendLine($"{indent}{{");

        var subIndent = indent + "    ";

        // Resolve a guaranteed-unique field name for every control once, so the four
        // generation passes below never emit duplicate variable names.
        var fieldNameMap = BuildFieldNameMap(className);

        // Field declarations
        foreach (var kvp in fieldNameMap)
        {
            if (kvp.Key == _surface.RootControl) continue;
            string typeName = kvp.Key.GetType().Name;
            sb.AppendLine($"{subIndent}private {typeName} {kvp.Value};");
        }

        sb.AppendLine();

        // InitializeComponent method
        sb.AppendLine($"{subIndent}private void {GeneratedClassName}()");
        sb.AppendLine($"{subIndent}{{");

        var bodyIndent = subIndent + "    ";

        // Create control instances
        foreach (var item in _surface.Items)
        {
            if (item.Control == _surface.RootControl) continue;
            var control = item.Control;
            string fieldName = fieldNameMap[control];
            string typeName = control.GetType().Name;
            sb.AppendLine($"{bodyIndent}{fieldName} = new {typeName}();");
        }

        sb.AppendLine();
        sb.AppendLine($"{bodyIndent}SuspendLayout();");

        // Configure each control
        foreach (var kvp in fieldNameMap)
        {
            if (kvp.Key == _surface.RootControl) continue;
            var control = kvp.Key;
            string fieldName = kvp.Value;

            sb.AppendLine();
            sb.AppendLine($"{bodyIndent}//");
            sb.AppendLine($"{bodyIndent}// {fieldName}");
            sb.AppendLine($"{bodyIndent}//");

            GeneratePropertyAssignments(sb, bodyIndent, control, fieldName);

            if (control is DataGridView dataGridView)
                GenerateDataGridViewColumns(sb, bodyIndent, dataGridView, fieldName);

            if (control is ToolStrip toolStrip)
                GenerateToolStripItems(sb, bodyIndent, toolStrip, fieldName);

            if (control is MenuStrip menuStrip)
                GenerateMenuStripItems(sb, bodyIndent, menuStrip, fieldName);

            if (control is StatusStrip statusStrip)
                GenerateStatusStripItems(sb, bodyIndent, statusStrip, fieldName);

            if (control is TableLayoutPanel table)
                GenerateTableLayoutStyles(sb, bodyIndent, table, fieldName);
        }

        // Controls.Add hierarchy
        GenerateControlHierarchy(sb, bodyIndent, _surface, fieldNameMap);

        // Explicit table cell assignments must come after the controls exist and are
        // parented, mirroring the designer's drop-to-cell behaviour.
        foreach (var kvp in fieldNameMap)
        {
            if (kvp.Key is not TableLayoutPanel tbl) continue;
            foreach (Control child in tbl.Controls)
            {
                var cell = tbl.GetCellPosition(child);
                if (cell.HasValue && fieldNameMap.TryGetValue(child, out var childField))
                    sb.AppendLine($"{bodyIndent}{kvp.Value}.SetCellPosition({childField}, {cell.Value.Row}, {cell.Value.Col});");
            }
        }

        sb.AppendLine($"{bodyIndent}ResumeLayout(false);");
        sb.AppendLine($"{subIndent}}}");

        sb.AppendLine($"{indent}}}");

        if (!string.IsNullOrEmpty(namespaceName))
        {
            sb.AppendLine("}");
        }

        return sb.ToString();
    }

    private static void GeneratePropertyAssignments(StringBuilder sb, string indent, Control control, string fieldName)
    {
        var props = new (string Name, Func<string?> Value)[]
        {
            ("Location", () => FormatPoint(control.Location)),
            ("Size", () => FormatSize(control.Size)),
            ("Text", () => Quote(control.Text)),
            ("Name", () => Quote(control.Name)),
            ("BackColor", () => FormatColor(control.BackColor)),
            ("TabIndex", () => control.TabIndex.ToString()),
            ("TabStop", () => control.TabStop.ToLowerString()),
            ("Enabled", () => control.Enabled.ToLowerString()),
            ("Visible", () => control.Visible.ToLowerString()),
            ("Padding", () => FormatPadding(control.Padding)),
        };

        foreach (var (propName, valueFn) in props)
        {
            var value = valueFn();
            if (!string.IsNullOrEmpty(value))
            {
                sb.AppendLine($"{indent}{fieldName}.{propName} = {value};");
            }
        }

        GenerateTextAlign(sb, indent, control, fieldName);
    }

    /// <summary>
    /// Emits a <c>TextAlign</c> assignment for controls that expose a writable
    /// <see cref="ContentAlignment"/> property whose current value differs from the
    /// value a freshly created instance of the same control type carries.
    /// </summary>
    /// <param name="sb">The builder to append to.</param>
    /// <param name="indent">The current indentation.</param>
    /// <param name="control">The control whose alignment is serialized.</param>
    /// <param name="fieldName">The field name of the control.</param>
    private static void GenerateTextAlign(StringBuilder sb, string indent, Control control, string fieldName)
    {
        var prop = control.GetType().GetProperty("TextAlign", BindingFlags.Public | BindingFlags.Instance);
        if (prop == null || !prop.CanWrite || prop.PropertyType != typeof(ContentAlignment))
            return;

        var value = (ContentAlignment)prop.GetValue(control)!;
        var defaultValue = (ContentAlignment)prop.GetValue((Control)Activator.CreateInstance(control.GetType())!)!;

        if (value != defaultValue)
            sb.AppendLine($"{indent}{fieldName}.TextAlign = ContentAlignment.{value};");
    }

    /// <summary>
    /// Emits a <c>Columns.Add(new DataGridViewColumn { ... })</c> call for every column of
    /// the given grid, serializing each non-default property so designer-created columns
    /// round-trip into the generated <c>InitializeComponent</c>.
    /// </summary>
    /// <param name="sb">The builder to append to.</param>
    /// <param name="indent">The current indentation.</param>
    /// <param name="grid">The data grid whose columns are serialized.</param>
    /// <param name="fieldName">The field name of the data grid.</param>
    private static void GenerateDataGridViewColumns(StringBuilder sb, string indent, DataGridView grid, string fieldName)
    {
        if (grid.Columns.Count == 0) return;

        foreach (var column in grid.Columns)
        {
            var parts = new List<string>();
            if (!string.IsNullOrEmpty(column.Name)) parts.Add($"Name = {Quote(column.Name)}");
            if (!string.IsNullOrEmpty(column.HeaderText)) parts.Add($"HeaderText = {Quote(column.HeaderText)}");
            if (!string.IsNullOrEmpty(column.DataPropertyName)) parts.Add($"DataPropertyName = {Quote(column.DataPropertyName)}");
            if (column.Width != 100) parts.Add($"Width = {column.Width}");
            if (column.ReadOnly) parts.Add("ReadOnly = true");
            if (column.ValueType != null) parts.Add($"ValueType = typeof({FormatTypeName(column.ValueType)})");
            if (column.TextAlign != DataGridViewContentAlignment.Left) parts.Add($"TextAlign = DataGridViewContentAlignment.{column.TextAlign}");
            if (!string.IsNullOrEmpty(column.FormatString)) parts.Add($"FormatString = {Quote(column.FormatString)}");
            if (!column.Resizable) parts.Add("Resizable = false");
            if (!column.Sortable) parts.Add("Sortable = false");
            if (!column.Groupable) parts.Add("Groupable = false");
            if (column.SortOrder != SortOrder.None) parts.Add($"SortOrder = SortOrder.{column.SortOrder}");
            if (column.CellEditType != DataGridViewColumnEditType.None) parts.Add($"CellEditType = DataGridViewColumnEditType.{column.CellEditType}");
            if (column.Items != null && column.Items.Count > 0)
                parts.Add($"Items = new List<object> {{ {string.Join(", ", column.Items.Select(FormatObjectLiteral))} }}");
            if (column.ComboBoxDropDownStyle != DropDownStyle.DropDownList) parts.Add($"ComboBoxDropDownStyle = DropDownStyle.{column.ComboBoxDropDownStyle}");
            if (column.TrueValue != null) parts.Add($"TrueValue = {FormatObjectLiteral(column.TrueValue)}");
            if (column.FalseValue != null) parts.Add($"FalseValue = {FormatObjectLiteral(column.FalseValue)}");
            if (column.PickerFormat != DateTimePickerFormat.Short) parts.Add($"PickerFormat = DateTimePickerFormat.{column.PickerFormat}");
            if (!string.IsNullOrEmpty(column.PickerCustomFormat)) parts.Add($"PickerCustomFormat = {Quote(column.PickerCustomFormat)}");
            if (!string.IsNullOrEmpty(column.ButtonText)) parts.Add($"ButtonText = {Quote(column.ButtonText)}");
            if (column.ButtonIcon is SvgImage svg && !string.IsNullOrEmpty(svg.ResourceName))
                parts.Add($"ButtonIcon = SvgImage.FromSvgResource({Quote(svg.ResourceName)}, {svg.DefaultSize})");

            if (parts.Count == 0)
                sb.AppendLine($"{indent}{fieldName}.Columns.Add(new DataGridViewColumn());");
            else
                sb.AppendLine($"{indent}{fieldName}.Columns.Add(new DataGridViewColumn {{ {string.Join(", ", parts)} }});");
        }
    }

    /// <summary>
    /// Emits <c>RowStyles.Add(new TableLayoutStyle(SizeType.X, yf))</c> and
    /// <c>ColumnStyles.Add(...)</c> calls for every style of the given table layout
    /// panel so designer-created rows and columns round-trip into the generated
    /// <c>InitializeComponent</c>. A non-default <see cref="TableLayoutPanel.CellSpacing"/>
    /// is emitted as a <c>CellSpacing = new Padding(...)</c> assignment.
    /// </summary>
    /// <param name="sb">The builder to append to.</param>
    /// <param name="indent">The current indentation.</param>
    /// <param name="table">The table layout panel whose styles are serialized.</param>
    /// <param name="fieldName">The field name of the table layout panel.</param>
    private static void GenerateTableLayoutStyles(StringBuilder sb, string indent, TableLayoutPanel table, string fieldName)
    {
        var spacing = table.CellSpacing;
        if (spacing.Left != 0 || spacing.Top != 0 || spacing.Right != 0 || spacing.Bottom != 0)
            sb.AppendLine($"{indent}{fieldName}.CellSpacing = {FormatPadding(spacing)};");

        foreach (var style in table.RowStyles)
            sb.AppendLine($"{indent}{fieldName}.RowStyles.Add(new TableLayoutStyle(SizeType.{style.SizeType}, {style.Value.ToString("0.####", CultureInfo.InvariantCulture)}f));");

        foreach (var style in table.ColumnStyles)
            sb.AppendLine($"{indent}{fieldName}.ColumnStyles.Add(new TableLayoutStyle(SizeType.{style.SizeType}, {style.Value.ToString("0.####", CultureInfo.InvariantCulture)}f));");
    }

    /// <summary>
    /// Emits an <c>Items.Add(new ToolStripButton { ... })</c> call for every item of the
    /// given tool strip, serializing each non-default property so designer-created items
    /// round-trip into the generated <c>InitializeComponent</c>. Nested dropdown items are
    /// emitted as nested collection initializers.
    /// </summary>
    /// <param name="sb">The builder to append to.</param>
    /// <param name="indent">The current indentation.</param>
    /// <param name="toolStrip">The tool strip whose items are serialized.</param>
    /// <param name="fieldName">The field name of the tool strip.</param>
    private static void GenerateToolStripItems(StringBuilder sb, string indent, ToolStrip toolStrip, string fieldName)
    {
        if (toolStrip.Items.Count == 0) return;

        foreach (var item in toolStrip.Items)
            sb.AppendLine($"{indent}{fieldName}.Items.Add({FormatToolStripItemInitializer(item)});");
    }

    /// <summary>
    /// Formats a single <see cref="ToolStripItem"/> as an inline object-initializer
    /// expression (<c>new ToolStripButton { Text = "..." }</c>), emitting only properties
    /// that differ from a freshly created instance of the same item type.
    /// </summary>
    /// <param name="item">The item to serialize.</param>
    /// <returns>A C# object-initializer expression for the item.</returns>
    private static string FormatToolStripItemInitializer(ToolStripItem item)
    {
        var defaults = (ToolStripItem)Activator.CreateInstance(item.GetType())!;
        var parts = new List<string>();

        string text = item is ToolStripTextBox tb ? tb.Text : item.Text;
        if (!string.IsNullOrEmpty(text)) parts.Add($"Text = {Quote(text)}");
        if (!item.Enabled && defaults.Enabled) parts.Add("Enabled = false");
        if (!item.Visible && defaults.Visible) parts.Add("Visible = false");
        if (item.DisplayStyle != defaults.DisplayStyle) parts.Add($"DisplayStyle = ToolStripItemDisplayStyle.{item.DisplayStyle}");
        if (item.ImageScaling != defaults.ImageScaling) parts.Add($"ImageScaling = ToolStripItemImageScaling.{item.ImageScaling}");
        if (item.TextAlign != defaults.TextAlign) parts.Add($"TextAlign = ToolStripItemTextAlign.{item.TextAlign}");
        if (item.Image is SvgImage svg && !string.IsNullOrEmpty(svg.ResourceName))
            parts.Add($"Image = SvgImage.FromSvgResource({Quote(svg.ResourceName)}, {svg.DefaultSize})");
        else if (item.Image is SvgImage importedSvg && !string.IsNullOrEmpty(importedSvg.ImportedBase64))
            parts.Add($"Image = SvgImage.FromSvgBase64({Quote(importedSvg.ImportedBase64)}, {importedSvg.DefaultSize})");
        else if (item.Image is RasterImage raster && !string.IsNullOrEmpty(raster.ImportedBase64))
            parts.Add($"Image = RasterImage.FromBase64({Quote(raster.ImportedBase64)})");

        switch (item)
        {
            case ToolStripButton button:
                if (button.CheckOnClick) parts.Add("CheckOnClick = true");
                if (button.Checked) parts.Add("Checked = true");
                if (button.DropDownItems.Count > 0)
                    parts.Add($"DropDownItems = {{ {string.Join(", ", button.DropDownItems.Select(FormatToolStripItemInitializer))} }}");
                break;
            case ToolStripMenuItem menuItem:
                if (menuItem.DropDownItems.Count > 0)
                    parts.Add($"DropDownItems = {{ {string.Join(", ", menuItem.DropDownItems.Select(FormatToolStripItemInitializer))} }}");
                break;
            case ToolStripTextBox textBox:
                if (textBox.TextBoxWidth != 100) parts.Add($"TextBoxWidth = {textBox.TextBoxWidth}");
                if (textBox.UseSystemPasswordChar) parts.Add("UseSystemPasswordChar = true");
                break;
            case ToolStripLabel label:
                if (label.IsLink) parts.Add("IsLink = true");
                break;
        }

        string typeName = item.GetType().Name;
        return parts.Count == 0 ? $"new {typeName}()" : $"new {typeName} {{ {string.Join(", ", parts)} }}";
    }

    /// <summary>
    /// Emits <c>fieldName.Items.Add(...)</c> calls for each top-level menu item of a
    /// <see cref="MenuStrip"/>, reusing the tool strip item initializer formatter so
    /// nested <c>DropDownItems</c> are serialized as collection initializers.
    /// </summary>
    /// <param name="sb">The target builder.</param>
    /// <param name="indent">The current indentation.</param>
    /// <param name="menuStrip">The menu strip whose items are serialized.</param>
    /// <param name="fieldName">The generated field name of the menu strip.</param>
    private static void GenerateMenuStripItems(StringBuilder sb, string indent, MenuStrip menuStrip, string fieldName)
    {
        if (menuStrip.Items.Count == 0) return;

        foreach (var item in menuStrip.Items)
            sb.AppendLine($"{indent}{fieldName}.Items.Add({FormatToolStripItemInitializer(item)});");
    }

    /// <summary>
    /// Emits <c>fieldName.Items.Add(...)</c> calls for each status label of a
    /// <see cref="StatusStrip"/>.
    /// </summary>
    /// <param name="sb">The target builder.</param>
    /// <param name="indent">The current indentation.</param>
    /// <param name="statusStrip">The status strip whose labels are serialized.</param>
    /// <param name="fieldName">The generated field name of the status strip.</param>
    private static void GenerateStatusStripItems(StringBuilder sb, string indent, StatusStrip statusStrip, string fieldName)
    {
        if (statusStrip.Items.Count == 0) return;

        foreach (var label in statusStrip.Items)
            sb.AppendLine($"{indent}{fieldName}.Items.Add({FormatStatusLabelInitializer(label)});");
    }

    /// <summary>
    /// Formats a <see cref="ToolStripStatusLabel"/> as an inline object-initializer
    /// expression, emitting only properties that differ from a freshly created label.
    /// </summary>
    /// <param name="label">The status label to serialize.</param>
    /// <returns>A C# object-initializer expression for the label.</returns>
    private static string FormatStatusLabelInitializer(ToolStripStatusLabel label)
    {
        var defaults = new ToolStripStatusLabel();
        var parts = new List<string>();

        if (!string.IsNullOrEmpty(label.Text)) parts.Add($"Text = {Quote(label.Text)}");
        if (!label.Visible) parts.Add("Visible = false");
        if (label.ForeColor != defaults.ForeColor) parts.Add($"ForeColor = {FormatColor(label.ForeColor)}");

        return parts.Count == 0 ? "new ToolStripStatusLabel()" : $"new ToolStripStatusLabel {{ {string.Join(", ", parts)} }}";
    }

    /// <summary>
    /// Formats an arbitrary object value as a C# literal, preserving the common primitive
    /// types (string, bool, decimal, float, double and other formattable numerics).
    /// </summary>
    /// <param name="value">The value to format.</param>
    /// <returns>A C# literal string for the value.</returns>
    private static string FormatObjectLiteral(object value)
    {
        switch (value)
        {
            case null: return "null";
            case string s: return Quote(s);
            case bool b: return b ? "true" : "false";
            case decimal dec: return dec.ToString(CultureInfo.InvariantCulture) + "m";
            case float f: return f.ToString(CultureInfo.InvariantCulture) + "f";
            case double dbl: return dbl.ToString(CultureInfo.InvariantCulture);
            case IFormattable fmt: return fmt.ToString(null, CultureInfo.InvariantCulture);
            default: return Quote(value.ToString() ?? string.Empty);
        }
    }

    /// <summary>
    /// Formats a <see cref="Type"/> as a C# type reference, using keyword aliases for the
    /// common primitives and the fully qualified name otherwise.
    /// </summary>
    /// <param name="type">The type to format.</param>
    /// <returns>A C# type name usable inside <c>typeof(...)</c>.</returns>
    private static string FormatTypeName(Type type)
    {
        if (type == typeof(int)) return "int";
        if (type == typeof(long)) return "long";
        if (type == typeof(double)) return "double";
        if (type == typeof(float)) return "float";
        if (type == typeof(decimal)) return "decimal";
        if (type == typeof(bool)) return "bool";
        if (type == typeof(string)) return "string";
        return type.FullName ?? type.Name;
    }

    private static void GenerateControlHierarchy(
        StringBuilder sb,
        string indent,
        DesignSurface surface,
        IReadOnlyDictionary<Control, string> fieldNameMap)
    {
        sb.AppendLine();
        sb.AppendLine($"{indent}// Control hierarchy");
        sb.AppendLine();

        foreach (var kvp in fieldNameMap)
        {
            var control = kvp.Key;
            if (control == surface.RootControl) continue;
            string fieldName = kvp.Value;
            Control? parent = control.Parent;

            if (parent is TabControl tabPageParent)
            {
                string parentField = fieldNameMap[tabPageParent];
                sb.AppendLine($"{indent}{parentField}.TabPages.Add({fieldName});");
            }
            else if (parent != null && parent != surface && parent != surface.RootControl)
            {
                string parentField = fieldNameMap[parent];
                sb.AppendLine($"{indent}{parentField}.Controls.Add({fieldName});");
            }
            else
            {
                sb.AppendLine($"{indent}Controls.Add({fieldName});");
            }
        }
    }

    /// <summary>
    /// Resolves a guaranteed-unique, valid C# field name for every non-root control on the
    /// surface. The same map is reused by all generation passes so field names never diverge
    /// or collide between the field declarations, instantiations, property assignments and the
    /// control hierarchy.
    /// </summary>
    /// <param name="className">The name of the partial class being generated, reserved so a
    /// control can never shadow the class itself.</param>
    /// <returns>A mapping from each designed control to its unique field name.</returns>
    private Dictionary<Control, string> BuildFieldNameMap(string className)
    {
        var reserved = new HashSet<string>(ReservedKeywords, StringComparer.Ordinal);
        reserved.Add(GeneratedClassName);
        foreach (var property in ReservedPropertyNames)
            reserved.Add(property);
        if (!string.IsNullOrEmpty(className))
            reserved.Add(className);

        var map = new Dictionary<Control, string>();
        foreach (var item in _surface.Items)
        {
            if (item.Control == _surface.RootControl) continue;
            CollectFields(item.Control, map, reserved);
        }
        return map;
    }

    private static void CollectFields(Control control, Dictionary<Control, string> map, HashSet<string> reserved)
    {
        if (map.ContainsKey(control)) return;
        map[control] = BuildUniqueName(control, reserved);

        foreach (var child in control.Controls)
            CollectFields(child, map, reserved);

        if (control is TabControl tc)
        {
            foreach (var page in tc.TabPages)
                CollectFields(page, map, reserved);
        }
    }

    /// <summary>
    /// Assigns the next unused name for the given control, suffixing an incrementing counter
    /// on every collision (e.g. <c>button</c>, <c>button1</c>, <c>button2</c>).
    /// </summary>
    /// <param name="control">The control to name.</param>
    /// <param name="reserved">The set of names already taken or otherwise forbidden.</param>
    /// <returns>The unique field name for the control.</returns>
    private static string BuildUniqueName(Control control, HashSet<string> reserved)
    {
        string baseName = SanitizeIdentifier(ResolveBaseName(control));
        if (string.IsNullOrEmpty(baseName))
            baseName = "control";

        string name = baseName;
        int counter = 1;
        while (!reserved.Add(name))
            name = $"{baseName}{counter++}";

        return name;
    }

    /// <summary>
    /// Determines the preferred base name for a control: its <see cref="Control.Name"/> when
    /// set, otherwise the lower-cased type name (e.g. <c>Button</c> -&gt; <c>button</c>).
    /// </summary>
    /// <param name="control">The control to name.</param>
    /// <returns>The preferred, pre-sanitization base name.</returns>
    private static string ResolveBaseName(Control control)
    {
        if (!string.IsNullOrWhiteSpace(control.Name))
            return control.Name;

        // Generate a name based on type
        string typeName = control.GetType().Name;
        if (typeName.Length == 0)
            return typeName;
        return char.ToLowerInvariant(typeName[0]) + typeName[1..];
    }

    /// <summary>
    /// Converts an arbitrary string into a legal C# identifier by replacing illegal characters
    /// with underscores and prefixing an underscore when the result would otherwise start with a
    /// digit. An empty input yields an empty string.
    /// </summary>
    /// <param name="name">The raw name to sanitize.</param>
    /// <returns>A syntactically valid C# identifier, or an empty string when <paramref name="name"/>
    /// is null or empty.</returns>
    private static string SanitizeIdentifier(string name)
    {
        if (string.IsNullOrEmpty(name))
            return string.Empty;

        var chars = name.ToCharArray();
        for (int i = 0; i < chars.Length; i++)
        {
            bool identifierChar = char.IsLetterOrDigit(chars[i]) || chars[i] == '_';
            if (!identifierChar)
                chars[i] = '_';
        }

        string result = new string(chars);
        if (char.IsDigit(result[0]))
            result = "_" + result;
        return result;
    }

    private static string FormatPoint(Point p) => $"new Point({p.X}, {p.Y})";
    private static string FormatSize(Size s) => $"new Size({s.Width}, {s.Height})";

    private static string FormatPadding(Padding p)
        => p.Left == 0 && p.Top == 0 && p.Right == 0 && p.Bottom == 0
            ? string.Empty
            : $"new Padding({p.Left}, {p.Top}, {p.Right}, {p.Bottom})";
    private static string FormatColor(Color c)
    {
        // Emit named color references when they match known colors
        if (c.A == 255)
        {
            if (c == Color.White) return "Color.White";
            if (c == Color.Black) return "Color.Black";
            if (c == Color.Red) return "Color.Red";
            if (c == Color.Green) return "Color.Green";
            if (c == Color.Blue) return "Color.Blue";
            if (c == Color.Yellow) return "Color.Yellow";
            if (c == Color.Transparent) return "Color.Transparent";

            // SystemColors — resolved at runtime, not fixed RGB
            if (c == SystemColors.Control) return "SystemColors.Control";
            if (c == SystemColors.ControlText) return "SystemColors.ControlText";
            if (c == SystemColors.Window) return "SystemColors.Window";
            if (c == SystemColors.WindowText) return "SystemColors.WindowText";
            if (c == SystemColors.Highlight) return "SystemColors.Highlight";
            if (c == SystemColors.HighlightText) return "SystemColors.HighlightText";
            if (c == SystemColors.ActiveCaption) return "SystemColors.ActiveCaption";
            if (c == SystemColors.ActiveCaptionText) return "SystemColors.ActiveCaptionText";
            if (c == SystemColors.InactiveCaption) return "SystemColors.InactiveCaption";
            if (c == SystemColors.ControlLight) return "SystemColors.ControlLight";
            if (c == SystemColors.ControlDark) return "SystemColors.ControlDark";
            if (c == SystemColors.GrayText) return "SystemColors.GrayText";
        }
        else
        {
            if (c == Color.Transparent) return "Color.Transparent";
            if (c == Color.Empty) return "Color.Empty";
        }

        // Fall back to RGB for custom colors
        return $"Color.FromArgb({c.R}, {c.G}, {c.B}{(c.A < 255 ? $", {c.A}" : "")})";
    }
    private static string Quote(string s) => string.IsNullOrEmpty(s) ? "" : $"\"{EscapeString(s)}\"";
    private static string EscapeString(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "\\r").Replace("\t", "\\t");
}

