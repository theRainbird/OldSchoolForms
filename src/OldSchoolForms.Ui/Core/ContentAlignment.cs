namespace OldSchoolForms.Ui.Core;

/// <summary>
/// Defines positions for the alignment of content within a rectangular area.
/// </summary>
public enum ContentAlignment
{
    /// <summary>
    /// Content is aligned to the top-left corner.
    /// </summary>
    TopLeft,

    /// <summary>
    /// Content is aligned horizontally centered at the top.
    /// </summary>
    TopCenter,

    /// <summary>
    /// Content is aligned to the top-right corner.
    /// </summary>
    TopRight,

    /// <summary>
    /// Content is aligned vertically centered at the left edge.
    /// </summary>
    MiddleLeft,

    /// <summary>
    /// Content is aligned both horizontally and vertically centered.
    /// </summary>
    MiddleCenter,

    /// <summary>
    /// Content is aligned vertically centered at the right edge.
    /// </summary>
    MiddleRight,

    /// <summary>
    /// Content is aligned to the bottom-left corner.
    /// </summary>
    BottomLeft,

    /// <summary>
    /// Content is aligned horizontally centered at the bottom.
    /// </summary>
    BottomCenter,

    /// <summary>
    /// Content is aligned to the bottom-right corner.
    /// </summary>
    BottomRight
}
